"""### Image Augmentation"""

class DroneDataAugmentation:
    """
    Image augmentation for drone detection with bounding box transformations
    """

    def __init__(self,
                 rotation_range=15,
                 brightness_range=0.2,
                 contrast_range=0.2,
                 saturation_range=0.2,
                 hue_range=0.1,
                 zoom_range=0.15,
                 horizontal_flip=True,
                 noise_factor=0.05,
                 blur_probability=0.3):

        self.rotation_range = rotation_range
        self.brightness_range = brightness_range
        self.contrast_range = contrast_range
        self.saturation_range = saturation_range
        self.hue_range = hue_range
        self.zoom_range = zoom_range
        self.horizontal_flip = horizontal_flip
        self.noise_factor = noise_factor
        self.blur_probability = blur_probability

    def augment_image_and_boxes(self, image, boxes):
        """
        Apply augmentation to image and transform bounding boxes accordingly
        """
        # Ensure image is float32 and in [0,1] range
        if image.dtype != np.float32:
            image = image.astype(np.float32)
        if image.max() > 1.0:
            image = image / 255.0

        augmented_image = np.copy(image)
        augmented_boxes = np.copy(boxes)

        # Apply augmentations in sequence
        augmented_image, augmented_boxes = self._apply_horizontal_flip(augmented_image, augmented_boxes)
        augmented_image, augmented_boxes = self._apply_rotation(augmented_image, augmented_boxes)
        augmented_image, augmented_boxes = self._apply_zoom(augmented_image, augmented_boxes)
        augmented_image = self._apply_color_augmentation(augmented_image)
        augmented_image = self._apply_noise(augmented_image)
        augmented_image = self._apply_blur(augmented_image)

        # Ensure values are in valid range
        augmented_image = np.clip(augmented_image, 0, 1)

        return augmented_image, augmented_boxes

    def _apply_horizontal_flip(self, image, boxes):
        """Apply horizontal flip with probability 0.5"""
        if self.horizontal_flip and random.random() < 0.5:
            image = np.fliplr(image)
            # Transform bounding boxes
            for i in range(len(boxes)):
                if np.sum(np.abs(boxes[i])) > 0:  # Valid box
                    class_id, x_center, y_center, width, height = boxes[i]
                    # Flip x coordinate
                    x_center = 1.0 - x_center
                    boxes[i] = [class_id, x_center, y_center, width, height]
        return image, boxes

    def _apply_rotation(self, image, boxes):
        """Apply rotation with bounding box transformation"""
        if random.random() < 0.5:
            angle = random.uniform(-self.rotation_range, self.rotation_range)

            h, w = image.shape[:2]
            center = (w // 2, h // 2)

            # Create rotation matrix
            M = cv2.getRotationMatrix2D(center, angle, 1.0)

            # Apply rotation to image
            image = cv2.warpAffine(image, M, (w, h), borderMode=cv2.BORDER_REFLECT)

            # Transform bounding boxes
            for i in range(len(boxes)):
                if np.sum(np.abs(boxes[i])) > 0:  # Valid box
                    class_id, x_center, y_center, width, height = boxes[i]

                    # Convert to pixel coordinates
                    x_pixel = x_center * w
                    y_pixel = y_center * h

                    # Apply rotation to center point
                    point = np.array([x_pixel, y_pixel, 1])
                    rotated_point = M @ point

                    # Convert back to normalized coordinates
                    new_x = rotated_point[0] / w
                    new_y = rotated_point[1] / h

                    # Keep within bounds
                    new_x = np.clip(new_x, 0, 1)
                    new_y = np.clip(new_y, 0, 1)

                    boxes[i] = [class_id, new_x, new_y, width, height]

        return image, boxes

    def _apply_zoom(self, image, boxes):
        """Apply zoom with bounding box transformation"""
        if random.random() < 0.5:
            zoom_factor = random.uniform(1 - self.zoom_range, 1 + self.zoom_range)

            h, w = image.shape[:2]
            new_h, new_w = int(h * zoom_factor), int(w * zoom_factor)

            # Resize image
            resized = cv2.resize(image, (new_w, new_h), interpolation=cv2.INTER_LINEAR)

            # Create output image
            if zoom_factor > 1:  # Zoom in - crop center
                start_x = (new_w - w) // 2
                start_y = (new_h - h) // 2
                image = resized[start_y:start_y + h, start_x:start_x + w]

                # Adjust bounding boxes for cropping
                for i in range(len(boxes)):
                    if np.sum(np.abs(boxes[i])) > 0:  # Valid box
                        class_id, x_center, y_center, width, height = boxes[i]

                        # Adjust for crop offset
                        x_center = (x_center * new_w - start_x) / w
                        y_center = (y_center * new_h - start_y) / h
                        width = width * zoom_factor
                        height = height * zoom_factor

                        # Check if box is still within bounds
                        if (0 <= x_center <= 1 and 0 <= y_center <= 1 and
                            width > 0 and height > 0):
                            boxes[i] = [class_id, x_center, y_center, width, height]
                        else:
                            boxes[i] = [0, 0, 0, 0, 0]  # Mark as invalid

            else:  # Zoom out - pad
                image = np.zeros((h, w, image.shape[2]), dtype=image.dtype)
                start_x = (w - new_w) // 2
                start_y = (h - new_h) // 2
                image[start_y:start_y + new_h, start_x:start_x + new_w] = resized

                # Adjust bounding boxes for padding
                for i in range(len(boxes)):
                    if np.sum(np.abs(boxes[i])) > 0:  # Valid box
                        class_id, x_center, y_center, width, height = boxes[i]

                        # Adjust for zoom and padding
                        x_center = (x_center * new_w + start_x) / w
                        y_center = (y_center * new_h + start_y) / h
                        width = width * zoom_factor
                        height = height * zoom_factor

                        boxes[i] = [class_id, x_center, y_center, width, height]

        return image, boxes

    def _apply_color_augmentation(self, image):
        """Apply color space augmentations"""
        # Convert to HSV for better color manipulation
        hsv = cv2.cvtColor(image, cv2.COLOR_RGB2HSV)

        # Brightness adjustment
        if random.random() < 0.7:
            brightness_factor = random.uniform(1 - self.brightness_range, 1 + self.brightness_range)
            hsv[:, :, 2] = np.clip(hsv[:, :, 2] * brightness_factor, 0, 1)

        # Saturation adjustment
        if random.random() < 0.5:
            saturation_factor = random.uniform(1 - self.saturation_range, 1 + self.saturation_range)
            hsv[:, :, 1] = np.clip(hsv[:, :, 1] * saturation_factor, 0, 1)

        # Hue adjustment
        if random.random() < 0.3:
            hue_shift = random.uniform(-self.hue_range, self.hue_range)
            hsv[:, :, 0] = np.clip(hsv[:, :, 0] + hue_shift, 0, 1)

        # Convert back to RGB
        image = cv2.cvtColor(hsv, cv2.COLOR_HSV2RGB)

        # Contrast adjustment
        if random.random() < 0.5:
            contrast_factor = random.uniform(1 - self.contrast_range, 1 + self.contrast_range)
            image = np.clip((image - 0.5) * contrast_factor + 0.5, 0, 1)

        return image

    def _apply_noise(self, image):
        """Add random noise"""
        if random.random() < 0.3:
            noise = np.random.normal(0, self.noise_factor, image.shape)
            image = np.clip(image + noise, 0, 1)
        return image

    def _apply_blur(self, image):
        """Apply blur with probability"""
        if random.random() < self.blur_probability:
            # Convert to uint8 for OpenCV
            image_uint8 = (image * 255).astype(np.uint8)
            kernel_size = random.choice([3, 5])
            image_uint8 = cv2.GaussianBlur(image_uint8, (kernel_size, kernel_size), 0)
            image = image_uint8.astype(np.float32) / 255.0
        return image

def create_fast_rcnn_target(proposal_targets):
    """
    Create target vector from proposal targets with better error handling
    """
    if not proposal_targets:
        target = np.zeros(9, dtype=np.float32)
        target[0] = 1.0  # Background class
        return target

    # Find best positive sample, or best negative if no positives
    positive_samples = [t for t in proposal_targets if t.get('is_positive', False)]

    if positive_samples:
        # Sort by IoU and take best
        best_sample = max(positive_samples, key=lambda x: x.get('iou', 0))
    else:
        # Take best negative sample
        best_sample = max(proposal_targets, key=lambda x: x.get('iou', 0))

    # Create target vector
    target = np.zeros(9, dtype=np.float32)

    # One-hot encode class
    class_idx = best_sample.get('class', 0)
    if 0 <= class_idx < 5:
        target[class_idx] = 1.0
    else:
        target[0] = 1.0  # Default to background

    # Add bbox regression deltas
    deltas = best_sample.get('bbox_deltas', [0.0, 0.0, 0.0, 0.0])
    if len(deltas) == 4 and all(np.isfinite(deltas)):
        target[5:9] = deltas

    return target

def prepare_augmented_fast_rcnn_data(X, Y, augmentation_factor=2, num_proposals=100):
    """
    Prepare Fast R-CNN data with augmentation
    """
    print("Preparing augmented Fast R-CNN training data...")

    augmenter = DroneDataAugmentation()

    fast_rcnn_images = []
    fast_rcnn_targets = []

    total_samples = len(X) * (1 + augmentation_factor)
    processed = 0

    for i, (image, gt_boxes) in enumerate(zip(X, Y)):
        try:
            # Process original image
            proposals = selective_search_proposals(image, num_proposals)
            proposal_targets = generate_proposal_targets(proposals, gt_boxes)

            if proposal_targets:
                target = create_fast_rcnn_target(proposal_targets)
                fast_rcnn_images.append(image)
                fast_rcnn_targets.append(target)
                processed += 1

            # Process augmented versions
            for aug_idx in range(augmentation_factor):
                try:
                    aug_image, aug_boxes = augmenter.augment_image_and_boxes(image, gt_boxes)

                    # Generate proposals and targets for augmented image
                    aug_proposals = selective_search_proposals(aug_image, num_proposals)
                    aug_proposal_targets = generate_proposal_targets(aug_proposals, aug_boxes)

                    if aug_proposal_targets:
                        aug_target = create_fast_rcnn_target(aug_proposal_targets)
                        fast_rcnn_images.append(aug_image)
                        fast_rcnn_targets.append(aug_target)
                        processed += 1

                except Exception as e:
                    print(f"Error in augmentation {aug_idx} for sample {i}: {e}")
                    continue

            if (i + 1) % 20 == 0:
                print(f"Processed {i + 1}/{len(X)} original images, {processed}/{total_samples} total samples")

        except Exception as e:
            print(f"Error processing sample {i}: {e}")
            continue

    if not fast_rcnn_images:
        print("Warning: No valid samples generated!")
        return np.array([]), np.array([])

    print(f"Generated {len(fast_rcnn_images)} total samples ({len(X)} original + {len(fast_rcnn_images) - len(X)} augmented)")

    return np.array(fast_rcnn_images, dtype=np.float32), np.array(fast_rcnn_targets, dtype=np.float32)

"""## Fast R-CNN for Drone Detection

**Fast R-CNN** is a two-stage object detection framework specifically adapted for identifying and localizing drones in aerial imagery.

### **Stage 1: Region Proposal Generation**
The system generates ~200 candidate bounding boxes (region proposals) across the image using a sliding window approach with multiple scales (8%-64% of image area) and aspect ratios (0.4-2.5). This captures drones of various sizes and orientations without exhaustively checking every pixel location.

### **Stage 2: Classification and Localization**
Each proposal is processed through a shared CNN backbone (typically ResNet50) that extracts visual features. These features feed into two specialized heads:

1. **Classification Head**: Determines if the proposal contains a drone, airplane, helicopter, bird, or background (5 classes total)
2. **Bounding Box Regression Head**: Refines the proposal coordinates using learned offset deltas to precisely localize the detected object

### **Training Process**
The model learns from ground truth annotations by:
- **Positive samples**: Proposals with >50% overlap (IoU) with actual drone locations
- **Negative samples**: Proposals with <30% overlap (background)
- **Loss function**: Combines classification loss (cross-entropy) and localization loss (smooth L1)

### **Advantages for Drone Detection**
- **Multi-scale detection**: Captures drones from close-up to distant views
- **Precise localization**: Bbox regression provides accurate drone boundaries
- **Real-time capability**: Shared CNN features make it computationally efficient
- **Robust classification**: Distinguishes drones from similar objects like birds or aircraft

**Region proposal generation using sliding window approach**
"""

def selective_search_proposals(image, num_proposals=200):
    """
    Region proposal generation with better coverage and validation
    """
    height, width = image.shape[:2]
    proposals = []

    # Improved scales and aspect ratios for better object coverage
    scales = [0.08, 0.12, 0.16, 0.24, 0.32, 0.48, 0.64]
    aspect_ratios = [0.4, 0.6, 0.8, 1.0, 1.25, 1.6, 2.0, 2.5]

    for scale in scales:
        for aspect_ratio in aspect_ratios:
            # Calculate box dimensions
            box_area = scale * scale
            box_width = int(np.sqrt(box_area * aspect_ratio) * width)
            box_height = int(np.sqrt(box_area / aspect_ratio) * height)

            # Ensure minimum and maximum box sizes
            box_width = max(16, min(box_width, width - 1))
            box_height = max(16, min(box_height, height - 1))

            if box_width >= width or box_height >= height:
                continue

            # Generate proposals with overlap
            step_x = max(8, box_width // 6)
            step_y = max(8, box_height // 6)

            for x in range(0, width - box_width + 1, step_x):
                for y in range(0, height - box_height + 1, step_y):
                    if len(proposals) >= num_proposals:
                        break

                    # Calculate center coordinates and normalize
                    x_center = (x + box_width / 2) / width
                    y_center = (y + box_height / 2) / height
                    w_norm = box_width / width
                    h_norm = box_height / height

                    # Validate proposal bounds
                    if (x_center - w_norm/2 >= 0 and x_center + w_norm/2 <= 1 and
                        y_center - h_norm/2 >= 0 and y_center + h_norm/2 <= 1):
                        proposals.append([x_center, y_center, w_norm, h_norm])

                if len(proposals) >= num_proposals:
                    break
            if len(proposals) >= num_proposals:
                break
        if len(proposals) >= num_proposals:
            break

    # Add random proposals for diversity if needed
    while len(proposals) < num_proposals:
        # Generate valid random proposals
        w_norm = np.random.uniform(0.1, 0.6)
        h_norm = np.random.uniform(0.1, 0.6)
        x_center = np.random.uniform(w_norm/2, 1 - w_norm/2)
        y_center = np.random.uniform(h_norm/2, 1 - h_norm/2)
        proposals.append([x_center, y_center, w_norm, h_norm])

    return np.array(proposals[:num_proposals], dtype=np.float32)

"""**Calculate bounding box regression deltas**"""

def calculate_bbox_deltas(proposal, gt_box):
    """
    Calculate bounding box regression deltas with proper error handling
    """
    try:
        # Convert to numpy arrays and validate
        proposal = np.array(proposal, dtype=np.float32).flatten()
        gt_box = np.array(gt_box, dtype=np.float32).flatten()

        if len(proposal) != 4 or len(gt_box) != 4:
            return [0.0, 0.0, 0.0, 0.0]

        # Extract coordinates
        px, py, pw, ph = proposal
        gx, gy, gw, gh = gt_box

        # Avoid division by zero and log of zero/negative numbers
        if pw <= 0 or ph <= 0 or gw <= 0 or gh <= 0:
            return [0.0, 0.0, 0.0, 0.0]

        # Calculate deltas (standard R-CNN formulation)
        dx = (gx - px) / pw
        dy = (gy - py) / ph
        dw = np.log(gw / pw)
        dh = np.log(gh / ph)

        # Ensure all values are finite
        deltas = [dx, dy, dw, dh]
        if not all(np.isfinite(deltas)):
            return [0.0, 0.0, 0.0, 0.0]

        return [float(d) for d in deltas]

    except Exception as e:
        # print(f"Bbox delta calculation error: {e}")
        return [0.0, 0.0, 0.0, 0.0]

"""**Calculate IoU between proposal and ground truth box**"""

def calculate_proposal_iou(proposal, gt_box):
    """
    IoU calculation with proper coordinate handling and validation
    """
    try:
        # Convert inputs to numpy arrays and validate
        proposal = np.array(proposal, dtype=np.float32).flatten()
        gt_box = np.array(gt_box, dtype=np.float32).flatten()

        # Ensure we have exactly 4 coordinates
        if len(proposal) != 4 or len(gt_box) != 4:
            return 0.0

        # Check for invalid boxes (negative dimensions or all zeros)
        if (proposal[2] <= 0 or proposal[3] <= 0 or
            gt_box[2] <= 0 or gt_box[3] <= 0):
            return 0.0

        if np.sum(np.abs(proposal)) == 0 or np.sum(np.abs(gt_box)) == 0:
            return 0.0

        # Convert center format to corner format
        def center_to_corners(box):
            x_center, y_center, width, height = box
            x1 = x_center - width / 2.0
            y1 = y_center - height / 2.0
            x2 = x_center + width / 2.0
            y2 = y_center + height / 2.0
            return x1, y1, x2, y2

        # Get corner coordinates
        p_x1, p_y1, p_x2, p_y2 = center_to_corners(proposal)
        gt_x1, gt_y1, gt_x2, gt_y2 = center_to_corners(gt_box)

        # Calculate intersection
        inter_x1 = max(p_x1, gt_x1)
        inter_y1 = max(p_y1, gt_y1)
        inter_x2 = min(p_x2, gt_x2)
        inter_y2 = min(p_y2, gt_y2)

        # Check for valid intersection
        if inter_x2 <= inter_x1 or inter_y2 <= inter_y1:
            return 0.0

        intersection = (inter_x2 - inter_x1) * (inter_y2 - inter_y1)

        # Calculate areas
        area_p = (p_x2 - p_x1) * (p_y2 - p_y1)
        area_gt = (gt_x2 - gt_x1) * (gt_y2 - gt_y1)

        # Ensure positive areas
        if area_p <= 0 or area_gt <= 0:
            return 0.0

        union = area_p + area_gt - intersection

        if union <= 0:
            return 0.0

        iou = intersection / union

        # Ensure single float return value
        if isinstance(iou, np.ndarray):
            iou = float(iou.item())
        else:
            iou = float(iou)

        # Clamp to valid range
        return max(0.0, min(1.0, iou))

    except Exception as e:
        # print(f"IoU calculation error: {e}")
        return 0.0

"""**Generate training targets for proposals based on ground truth**"""

def generate_proposal_targets(proposals, ground_truth_boxes,
                                  positive_iou_threshold=0.5,
                                  negative_iou_threshold=0.3):
    """
    Proposal target generation with robust error handling
    """
    targets = []

    # Validate and process ground truth boxes
    valid_gt_boxes = []
    for box in ground_truth_boxes:
        try:
            box = np.array(box, dtype=np.float32).flatten()
            if len(box) >= 5 and np.sum(np.abs(box[1:5])) > 0:
                # Ensure valid box format [class, x, y, w, h]
                class_id = int(box[0])
                coords = box[1:5]
                if coords[2] > 0 and coords[3] > 0:  # positive width and height
                    valid_gt_boxes.append((class_id, coords))
        except (ValueError, TypeError, IndexError):
            continue

    for proposal in proposals:
        try:
            proposal = np.array(proposal, dtype=np.float32).flatten()
            if len(proposal) != 4:
                continue

            best_iou = 0.0
            best_class = 0  # Background class
            best_gt_coords = None

            # Find best matching ground truth box
            for class_id, gt_coords in valid_gt_boxes:
                iou = calculate_proposal_iou(proposal, gt_coords)

                if iou > best_iou:
                    best_iou = iou
                    best_class = class_id + 1  # +1 because 0 is background
                    best_gt_coords = gt_coords

            # Create target based on IoU thresholds
            if best_iou >= positive_iou_threshold and best_gt_coords is not None:
                # Positive sample
                bbox_deltas = calculate_bbox_deltas(proposal, best_gt_coords)
                target = {
                    'class': best_class,
                    'bbox': best_gt_coords.copy(),
                    'bbox_deltas': bbox_deltas,
                    'is_positive': True,
                    'iou': best_iou
                }
            elif best_iou < negative_iou_threshold:
                # Negative sample (clear background)
                target = {
                    'class': 0,  # Background
                    'bbox': proposal.copy(),
                    'bbox_deltas': [0.0, 0.0, 0.0, 0.0],
                    'is_positive': False,
                    'iou': best_iou
                }
            else:
                # Ignore samples (ambiguous cases) - treat as background for simplicity
                target = {
                    'class': 0,  # Background
                    'bbox': proposal.copy(),
                    'bbox_deltas': [0.0, 0.0, 0.0, 0.0],
                    'is_positive': False,
                    'iou': best_iou
                }

            targets.append(target)

        except Exception as e:
            # Add default background target
            targets.append({
                'class': 0,
                'bbox': proposal.copy() if len(proposal) == 4 else [0.5, 0.5, 0.1, 0.1],
                'bbox_deltas': [0.0, 0.0, 0.0, 0.0],
                'is_positive': False,
                'iou': 0.0
            })

    return targets

"""**Create Fast R-CNN model architecture**"""

def create_fast_rcnn_model(num_classes=5, input_shape=(224, 224, 3)):
    """
    Fast R-CNN model architecture
    """
    inputs = Input(shape=input_shape, name='image_input')

    # Enhanced feature extraction backbone
    x = Conv2D(64, (3, 3), activation='relu', padding='same')(inputs)
    x = BatchNormalization()(x)
    x = Conv2D(64, (3, 3), activation='relu', padding='same')(x)
    x = MaxPooling2D((2, 2))(x)
    x = Dropout(0.25)(x)

    x = Conv2D(128, (3, 3), activation='relu', padding='same')(x)
    x = BatchNormalization()(x)
    x = Conv2D(128, (3, 3), activation='relu', padding='same')(x)
    x = MaxPooling2D((2, 2))(x)
    x = Dropout(0.25)(x)

    x = Conv2D(256, (3, 3), activation='relu', padding='same')(x)
    x = BatchNormalization()(x)
    x = Conv2D(256, (3, 3), activation='relu', padding='same')(x)
    x = MaxPooling2D((2, 2))(x)
    x = Dropout(0.25)(x)

    x = Conv2D(512, (3, 3), activation='relu', padding='same')(x)
    x = BatchNormalization()(x)
    x = GlobalAveragePooling2D()(x)

    # Shared dense layers with better regularization
    x = Dense(1024, activation='relu')(x)
    x = BatchNormalization()(x)
    x = Dropout(0.5)(x)

    x = Dense(512, activation='relu')(x)
    x = BatchNormalization()(x)
    x = Dropout(0.3)(x)

    # Output heads
    classification_output = Dense(num_classes, activation='softmax', name='classification')(x)
    bbox_output = Dense(4, activation='linear', name='bbox_regression')(x)

    model = Model(inputs=inputs, outputs=[classification_output, bbox_output])
    return model

"""**Prepare data for Fast R-CNN training**"""

def prepare_fast_rcnn_data(X, Y, num_proposals=100, positive_fraction=0.25):
    """
    Fast R-CNN data preparation with balanced sampling and error handling
    """
    print("Preparing Fast R-CNN training data...")

    fast_rcnn_images = []
    fast_rcnn_targets = []

    for i, (image, gt_boxes) in enumerate(zip(X, Y)):
        try:
            # Validate image
            if image is None or image.size == 0:
                continue

            # Generate region proposals
            proposals = selective_search_proposals(image, num_proposals)

            # Generate targets for proposals
            proposal_targets = generate_proposal_targets(proposals, gt_boxes)

            if not proposal_targets:
                # Fallback: create background sample
                target = np.zeros(9, dtype=np.float32)
                target[0] = 1.0  # Background class
                fast_rcnn_targets.append(target)
                fast_rcnn_images.append(image)
                continue

            # Separate positive and negative samples
            positive_samples = [t for t in proposal_targets if t['is_positive'] and t['class'] > 0]
            negative_samples = [t for t in proposal_targets if t['class'] == 0]

            # Balance positive and negative samples
            max_positives = min(len(positive_samples), max(1, int(num_proposals * positive_fraction)))
            max_negatives = min(len(negative_samples), max(1, num_proposals - max_positives))

            # Sort by IoU to get best samples
            if positive_samples:
                positive_samples.sort(key=lambda x: x.get('iou', 0), reverse=True)
                selected_positives = positive_samples[:max_positives]
            else:
                selected_positives = []

            if negative_samples:
                negative_samples.sort(key=lambda x: x.get('iou', 0))
                selected_negatives = negative_samples[:max_negatives]
            else:
                selected_negatives = []

            # Choose best sample for this image
            if selected_positives:
                best_sample = selected_positives[0]
            elif selected_negatives:
                best_sample = selected_negatives[0]
            else:
                # Fallback
                best_sample = {
                    'class': 0,
                    'bbox_deltas': [0.0, 0.0, 0.0, 0.0],
                    'is_positive': False
                }

            # Create target vector: [one_hot_class(5) + bbox_deltas(4)] = 9 elements
            target = np.zeros(9, dtype=np.float32)

            # One-hot encode class
            class_idx = best_sample.get('class', 0)
            if 0 <= class_idx < 5:
                target[class_idx] = 1.0
            else:
                target[0] = 1.0  # Default to background

            # Add bbox regression deltas
            deltas = best_sample.get('bbox_deltas', [0.0, 0.0, 0.0, 0.0])
            if len(deltas) == 4:
                target[5:9] = deltas

            fast_rcnn_targets.append(target)
            fast_rcnn_images.append(image)

        except Exception as e:
            print(f"Error processing sample {i}: {e}")
            # Add fallback sample
            target = np.zeros(9, dtype=np.float32)
            target[0] = 1.0  # Background
            fast_rcnn_targets.append(target)
            fast_rcnn_images.append(image if image is not None else np.zeros((224, 224, 3)))
            continue

        if (i + 1) % 50 == 0:
            print(f"Processed {i + 1}/{len(X)} images for Fixed Fast R-CNN")

    if not fast_rcnn_images:
        print("Warning: No valid samples generated!")
        return np.array([]), np.array([])

    return np.array(fast_rcnn_images, dtype=np.float32), np.array(fast_rcnn_targets, dtype=np.float32)

"""**Calculate classification and bounding-box regression**"""

def classification_loss(y_true, y_pred):
    """
    Classification loss
    """
    return tf.keras.losses.categorical_crossentropy(y_true, y_pred)

def bbox_regression_loss(y_true, y_pred):
    """
    Smooth L1 loss for bounding box regression
    """
    diff = y_true - y_pred
    abs_diff = tf.abs(diff)

    # Smooth L1 loss
    smooth_l1 = tf.where(
        abs_diff < 1.0,
        0.5 * tf.square(diff),
        abs_diff - 0.5
    )

    return tf.reduce_mean(smooth_l1)

