    ax.set_title(title, fontsize=14)
    ax.legend(frameon=True, framealpha=0.9, facecolor='white', fontsize=10)
    ax.grid(True)
    ax.tick_params(axis='x', rotation=10)
    plt.savefig('images/loss_function_metrics.png')

