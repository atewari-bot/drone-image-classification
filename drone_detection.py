"""**Evaluate Fast R-CNN model performance**"""

def evaluate_fast_rcnn(model, X_test, Y_test, num_samples=50):
    """
    Evaluate Fast R-CNN model performance
    """
    try:
        print("Evaluating Fast R-CNN model...")

        # Prepare test data
        X_test_frcnn, Y_test_frcnn = prepare_fast_rcnn_data(X_test[:num_samples], Y_test[:num_samples])

        if len(X_test_frcnn) == 0:
            print("No valid test data!")
            return 0.0, 0.0, 0.0

        # Get predictions
        predictions = model.predict(X_test_frcnn, verbose=0)
        pred_classes = predictions[0]
        pred_bboxes = predictions[1]

        # Calculate classification accuracy
        Y_test_cls = Y_test_frcnn[:, :5]
        pred_cls_labels = np.argmax(pred_classes, axis=1)
        true_cls_labels = np.argmax(Y_test_cls, axis=1)

        classification_accuracy = np.mean(true_cls_labels == pred_cls_labels)

        # Calculate bbox regression metrics
        Y_test_bbox = Y_test_frcnn[:, 5:9]
        bbox_mse = np.mean((Y_test_bbox - pred_bboxes) ** 2)
        bbox_mae = np.mean(np.abs(Y_test_bbox - pred_bboxes))

        print(f"Classification Accuracy: {classification_accuracy:.4f}")
        print(f"Bbox MSE: {bbox_mse:.4f}")
        print(f"Bbox MAE: {bbox_mae:.4f}")

        return classification_accuracy, bbox_mse, bbox_mae

    except Exception as e:
        print(f"Evaluation error: {e}")
        return 0.0, 0.0, 0.0

